        INSERT INTO assets (id, asset_code, name, department_id)
        SELECT id, 'OTHER-CODE', 'Duplicate Internal Identity', department_id
        FROM assets WHERE asset_code = 'PRJ-001';
        RAISE EXCEPTION 'A duplicate UUID primary key was incorrectly accepted';
    EXCEPTION WHEN unique_violation THEN
        GET STACKED DIAGNOSTICS violated = CONSTRAINT_NAME;
        IF violated IS DISTINCT FROM 'pk_assets' THEN RAISE; END IF;
        RAISE NOTICE 'Expected SQLSTATE 23505 on % despite a different asset code.', violated;
    END;
END $$;
\echo PASS: A different asset code cannot bypass UUID primary-key uniqueness.

