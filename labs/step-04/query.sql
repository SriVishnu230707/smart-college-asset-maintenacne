-- DO/EXCEPTION blocks are verification plumbing: they catch only the expected
-- SQLSTATE/constraint, allowing the outer demonstration transaction to continue.
-- Any unexpected error or accepted bad input fails the complete exercise.
\echo === A fresh UUID does not permit a duplicate asset code ===
DO $$
DECLARE candidate uuid := gen_random_uuid(); violated text;
BEGIN
    IF EXISTS (SELECT 1 FROM assets WHERE id = candidate) THEN
        RAISE EXCEPTION 'Candidate UUID must differ from all stored IDs for this proof';
    END IF;
    BEGIN
        INSERT INTO assets (id, asset_code, name, department_id)
        SELECT candidate, upper(btrim(' prj-001 ')), 'Duplicate Projector', department_id
        FROM assets WHERE asset_code = 'PRJ-001';
        RAISE EXCEPTION 'A duplicate canonical asset code was incorrectly accepted';
    EXCEPTION WHEN unique_violation THEN
        GET STACKED DIAGNOSTICS violated = CONSTRAINT_NAME;
        IF violated IS DISTINCT FROM 'uq_assets_asset_code' THEN RAISE; END IF;
        RAISE NOTICE 'Expected SQLSTATE 23505 on %; the candidate UUID was distinct.', violated;
    END;
END $$;
\echo PASS: A fresh UUID cannot bypass the independent unique asset_code constraint.

DO $$
DECLARE violated text;
BEGIN
    BEGIN
        INSERT INTO departments (code, name) VALUES ('CSE', 'Duplicate Department');
        RAISE EXCEPTION 'A duplicate department code was incorrectly accepted';
    EXCEPTION WHEN unique_violation THEN
        GET STACKED DIAGNOSTICS violated = CONSTRAINT_NAME;
        IF violated IS DISTINCT FROM 'uq_departments_code' THEN RAISE; END IF;
        RAISE NOTICE 'Expected SQLSTATE 23505 on %.', violated;
    END;
END $$;
\echo PASS: A generated UUID does not permit a duplicate department code.

DO $$
DECLARE violated text;
BEGIN
    BEGIN
        INSERT INTO spare_parts (sku, name) VALUES ('LAMP-001', 'Duplicate Lamp');
        RAISE EXCEPTION 'A duplicate SKU was incorrectly accepted';
    EXCEPTION WHEN unique_violation THEN
        GET STACKED DIAGNOSTICS violated = CONSTRAINT_NAME;
        IF violated IS DISTINCT FROM 'uq_spare_parts_sku' THEN RAISE; END IF;
        RAISE NOTICE 'Expected SQLSTATE 23505 on %.', violated;
    END;
END $$;
\echo PASS: A generated UUID does not permit a duplicate part SKU.

DO $$
DECLARE violated text;
BEGIN
