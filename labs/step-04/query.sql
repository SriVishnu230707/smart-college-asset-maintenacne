CREATE TABLE departments (
    id uuid DEFAULT gen_random_uuid() CONSTRAINT pk_departments PRIMARY KEY,
    code varchar(20) NOT NULL CONSTRAINT uq_departments_code UNIQUE,
    name varchar(150) NOT NULL,
    is_archived boolean NOT NULL DEFAULT false
);
CREATE TABLE assets (
    id uuid DEFAULT gen_random_uuid() CONSTRAINT pk_assets PRIMARY KEY,
    asset_code varchar(50) NOT NULL CONSTRAINT uq_assets_asset_code UNIQUE,
    name varchar(150) NOT NULL,
    department_id uuid NOT NULL REFERENCES departments(id)
);
CREATE TABLE spare_parts (
    id uuid DEFAULT gen_random_uuid() CONSTRAINT pk_spare_parts PRIMARY KEY,
    sku varchar(50) NOT NULL CONSTRAINT uq_spare_parts_sku UNIQUE,
    name varchar(150) NOT NULL,
    is_archived boolean NOT NULL DEFAULT false
);
-- The following tables compare types/generators; they are not application entities.
CREATE TABLE identity_always (
    id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    label text NOT NULL CONSTRAINT uq_identity_always_label UNIQUE
);
CREATE TABLE identity_by_default (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    label text NOT NULL
);
CREATE TABLE type_probe (
    short_label varchar(4) PRIMARY KEY,
    details text NOT NULL,
    is_active boolean NOT NULL DEFAULT true
);

