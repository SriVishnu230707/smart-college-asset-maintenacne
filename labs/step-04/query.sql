DO $$
DECLARE violated text;
BEGIN
    BEGIN
        INSERT INTO identity_always (label) VALUES ('first');
        RAISE EXCEPTION 'A duplicate comparison label was incorrectly accepted';
    EXCEPTION WHEN unique_violation THEN
        GET STACKED DIAGNOSTICS violated = CONSTRAINT_NAME;
        IF violated IS DISTINCT FROM 'uq_identity_always_label' THEN RAISE; END IF;
        RAISE NOTICE 'Expected SQLSTATE 23505; its allocated identity value is not reclaimed.';
